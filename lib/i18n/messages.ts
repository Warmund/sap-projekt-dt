export function translate(language: Language, message: string, ...args: (string | number | undefined)[]) {
  const text = language === "en" && Object.hasOwn(english, message) ? english[message] : message;
  return args.length ? text.replace(/\{(\d+)\}/g, (_, index: string) => String(args[Number(index)] ?? "")) : text;
}

type Translator = (message: string, ...args: (string | number | undefined)[]) => string;

export function translateStepResult(result: string, t: Translator) {
  const counts = /^(\d+) von (\d+) Tenants gesperrt$/.exec(result);
  return counts ? t("{0} von {1} Tenants gesperrt", counts[1], counts[2]) : t(result);
}

export function translateAudit(text: string, t: Translator): string {
  const imported = /^Aus (.+), Datensatz (\d+) übernommen\. CRM als BP-ID; Freigabe und Sperrschritte nicht in der Quelle enthalten\.$/.exec(text);
  if (imported) {
    return t("Aus {0}, Datensatz {1} übernommen. CRM als BP-ID; Freigabe und Sperrschritte nicht in der Quelle enthalten.", imported[1], imported[2]);
  }
  const variant = /^Schrittfolge auf Variante ([AB]) gesetzt\.$/.exec(text);
  if (variant) return t("Schrittfolge auf Variante {0} gesetzt.", variant[1]);
  if (text.startsWith("SIMULIERT: ")) return t("SIMULIERT: {0}", translateAudit(text.slice("SIMULIERT: ".length), t));
  const separator = text.indexOf(": ");
  if (separator === -1) return translateStepResult(text, t);
  const title = text.slice(0, separator);
  const detail = text.slice(separator + 2);
  return `${t(title)}: ${title.startsWith("Freigegeben") || title.startsWith("Bestätigt") || title.startsWith("Abgelehnt") ? detail : translateStepResult(detail, t)}`;
}
