import { expect, test } from "@playwright/test";

test("personal tasks can be created, filtered, completed and deleted", async ({ page }) => {
  test.setTimeout(90_000);
  test.skip(!process.env.TEST_USERNAME || !process.env.TEST_PASSWORD, "Set TEST_USERNAME and TEST_PASSWORD for a dedicated demo account.");
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/login");
  await page.getByLabel("Benutzername").fill(process.env.TEST_USERNAME!);
  await page.getByLabel("Passwort").fill(process.env.TEST_PASSWORD!);
  await page.getByRole("button", { name: "Anmelden", exact: true }).click();
  await expect(page).toHaveURL("/", { timeout: 30_000 });
  await expect(page.getByRole("heading", { name: "Mein Arbeitsplatz", exact: true })).toBeVisible();
  const list = page.getByRole("list", { name: "Aufgaben", exact: true });
  await expect(list.getByRole("listitem")).toHaveCount(5);
  await expect(page.getByRole("button", { name: "Collapse Header", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Collapse Header", exact: true }).click();
  await expect(page.locator("ui5-dynamic-page")).toHaveJSProperty("headerSnapped", true);
  await page.getByRole("button", { name: "Expand Header", exact: true }).click();
  await expect(page.locator("ui5-dynamic-page")).toHaveJSProperty("headerSnapped", false);
  await page.screenshot({ path: ".scratch/workspace-desktop.png", fullPage: true });
  const title = "Browser-Test: Nächsten Schritt planen";
  const field = page.getByRole("textbox", { name: "Neue Aufgabe", exact: true });
  await field.fill("   ");
  await expect(page.getByRole("button", { name: "Hinzufügen", exact: true })).toBeDisabled();
  await field.fill(title);
  await page.getByRole("combobox", { name: "Priorität", exact: true }).click();
  await page.getByRole("option", { name: "Hoch", exact: true }).click();
  await page.getByRole("button", { name: "Hinzufügen", exact: true }).click();
  await expect(list.getByRole("listitem")).toHaveCount(6);
  await expect(list.getByRole("listitem").filter({ hasText: title }).getByText("Hoch", { exact: true })).toBeVisible();
  await page.reload();
  await expect(list.getByText(title, { exact: true })).toBeVisible();
  await page.getByRole("textbox", { name: "Aufgaben suchen", exact: true }).fill(title);
  await expect(list.getByRole("listitem")).toHaveCount(1);
  await page.getByRole("checkbox", { name: `${title} als erledigt markieren`, exact: true }).click();
  await expect(page.getByRole("checkbox", { name: `${title} als offen markieren`, exact: true })).toBeChecked();
  await page.locator('ui5-segmented-button-item[data-filter="open"]').click();
  await expect(list.getByRole("listitem")).toHaveCount(0);
  await page.locator('ui5-segmented-button-item[data-filter="done"]').click();
  await expect(list.getByText(title, { exact: true })).toBeVisible();
  await page.getByRole("button", { name: `Aufgabe löschen: ${title}`, exact: true }).click();
  await expect(list.getByRole("listitem")).toHaveCount(0);
  await page.getByRole("textbox", { name: "Aufgaben suchen", exact: true }).fill("");
  await page.locator('ui5-segmented-button-item[data-filter="all"]').click();
  await page.setViewportSize({ width: 375, height: 812 });
  await page.getByRole("button", { name: "Neue Aufgabe", exact: true }).click();
  await expect(field).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(await page.locator("ui5-dynamic-page").evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: ".scratch/workspace-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "Abmelden", exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  expect(errors).toEqual([]);
});
